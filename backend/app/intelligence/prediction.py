import os
import json
import logging
from typing import Dict, Any, Optional
import joblib
import numpy as np

logger = logging.getLogger("worksense.ml")

MODEL_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../ml/saved_models"))
RF_MODEL_PATH = os.path.join(MODEL_DIR, "rf_effort_model.pkl")
ISO_MODEL_PATH = os.path.join(MODEL_DIR, "isolation_forest_model.pkl")
METADATA_PATH = os.path.join(MODEL_DIR, "model_metadata.json")

class MLEngine:
    def __init__(self):
        self.rf_model = None
        self.iso_model = None
        self.metadata = {}
        self.load_models()

    def load_models(self):
        try:
            if os.path.exists(RF_MODEL_PATH):
                self.rf_model = joblib.load(RF_MODEL_PATH)
                logger.info(f"Loaded Random Forest model from {RF_MODEL_PATH}")
            if os.path.exists(ISO_MODEL_PATH):
                self.iso_model = joblib.load(ISO_MODEL_PATH)
                logger.info(f"Loaded Isolation Forest model from {ISO_MODEL_PATH}")
            if os.path.exists(METADATA_PATH):
                with open(METADATA_PATH, "r") as f:
                    self.metadata = json.load(f)
        except Exception as e:
            logger.error(f"Failed to load ML models: {e}")

    def get_status(self) -> Dict[str, Any]:
        return {
            "model_loaded": self.rf_model is not None,
            "anomaly_detector_loaded": self.iso_model is not None,
            "model_type": self.metadata.get("model_type", "RandomForestRegressor"),
            "features": self.metadata.get("features", []),
            "evaluation_metrics": self.metadata.get("evaluation_metrics", {}),
            "is_synthetic": self.metadata.get("is_synthetic", True),
            "disclaimer": self.metadata.get("disclaimer", "Historical completion data required for full production calibration."),
            "trained_at": self.metadata.get("trained_at", None)
        }

    def predict_effort(
        self,
        complexity: str,
        priority: str,
        estimated_hours: float,
        dev_experience: str = "mid",
        required_skills_count: int = 2,
        avg_skill_proficiency: float = 3.5
    ) -> Dict[str, Any]:
        """
        Predicts actual completion hours using the trained Random Forest model.
        """
        complexity_map = {"easy": 1, "medium": 2, "hard": 3, "critical": 4}
        priority_map = {"low": 1, "medium": 2, "high": 3, "critical": 4}
        experience_map = {"junior": 1, "mid": 2, "senior": 3, "lead": 4}

        c_num = complexity_map.get(complexity.strip().lower(), 2)
        p_num = priority_map.get(priority.strip().lower(), 2)
        exp_num = experience_map.get(dev_experience.strip().lower(), 2)

        input_features = np.array([[
            c_num,
            p_num,
            float(estimated_hours),
            exp_num,
            int(required_skills_count),
            float(avg_skill_proficiency)
        ]])

        if self.rf_model:
            predicted_hours = float(self.rf_model.predict(input_features)[0])
        else:
            # Fallback heuristic calculation if model not yet loaded
            exp_mult = {1: 1.35, 2: 1.10, 3: 0.90, 4: 0.80}.get(exp_num, 1.0)
            predicted_hours = float(estimated_hours) * exp_mult

        predicted_hours = round(max(0.5, predicted_hours), 1)
        variance_vs_estimate = round(predicted_hours - float(estimated_hours), 1)

        confidence_interval = [
            round(max(0.5, predicted_hours - 1.8), 1),
            round(predicted_hours + 1.8, 1)
        ]

        risk_level = "low"
        if variance_vs_estimate > 6.0 or (predicted_hours > float(estimated_hours) * 1.4):
            risk_level = "high"
        elif variance_vs_estimate > 2.0:
            risk_level = "moderate"

        return {
            "estimated_hours": float(estimated_hours),
            "predicted_actual_hours": predicted_hours,
            "variance_hours": variance_vs_estimate,
            "confidence_interval_hours": confidence_interval,
            "risk_level": risk_level,
            "factors": {
                "complexity": complexity,
                "priority": priority,
                "dev_experience": dev_experience,
                "required_skills_count": required_skills_count,
                "avg_skill_proficiency": avg_skill_proficiency
            },
            "disclaimer": "Predicted completion hours generated by Random Forest model."
        }

    def train_on_database_records(self, db) -> Dict[str, Any]:
        """
        Extracts real completed task data and actual logged hours from the live database,
        and fine-tunes or trains the Random Forest effort prediction model.
        """
        from app.models.entities import Task, TimeLog, Developer, DeveloperSkill, TaskRequiredSkill, User
        from sqlalchemy import func
        from sklearn.ensemble import RandomForestRegressor
        from sklearn.metrics import mean_absolute_error, mean_squared_error
        import pandas as pd

        # Query all completed tasks that have actual hours logged
        completed_tasks = db.query(Task).filter(Task.status == "completed").all()
        training_samples = []

        complexity_map = {"easy": 1, "medium": 2, "hard": 3, "critical": 4}
        priority_map = {"low": 1, "medium": 2, "high": 3, "critical": 4}
        exp_map = {"junior": 1, "mid": 2, "senior": 3, "lead": 4}

        for t in completed_tasks:
            # Sum actual hours logged
            total_hours_res = db.query(func.coalesce(func.sum(TimeLog.hours_spent), 0.0)).filter(TimeLog.task_id == t.id).scalar()
            actual_hours = float(total_hours_res or 0.0)
            if actual_hours <= 0:
                continue

            # First assigned developer info
            assigned = t.assignments[0] if t.assignments else None
            dev_exp = 2
            avg_prof = 3.0
            if assigned and assigned.developer:
                dev = assigned.developer
                dev_exp = exp_map.get(dev.experience_level.lower(), 2)
                skills = db.query(DeveloperSkill).filter(DeveloperSkill.developer_id == dev.id).all()
                if skills:
                    avg_prof = float(sum(s.proficiency_level for s in skills) / len(skills))

            req_count = len(t.required_skills) if t.required_skills else 1

            training_samples.append({
                "complexity_num": complexity_map.get(t.complexity.lower(), 2),
                "priority_num": priority_map.get(t.priority.lower(), 2),
                "estimated_hours": float(t.estimated_hours),
                "dev_experience_num": dev_exp,
                "required_skills_count": req_count,
                "avg_skill_proficiency": avg_prof,
                "actual_hours": actual_hours
            })

        if len(training_samples) < 5:
            return {
                "success": False,
                "sample_count": len(training_samples),
                "message": (
                    f"Only {len(training_samples)} completed tasks with time logs found in database. "
                    "At least 5 completed tasks with recorded time logs are required to calibrate the ML model on real data. "
                    "Complete more tasks and record time logs to train exclusively on your team's real historical data."
                ),
                "current_model": self.get_status()
            }

        df = pd.DataFrame(training_samples)
        feature_cols = [
            "complexity_num",
            "priority_num",
            "estimated_hours",
            "dev_experience_num",
            "required_skills_count",
            "avg_skill_proficiency"
        ]
        X = df[feature_cols]
        y = df["actual_hours"]

        rf = RandomForestRegressor(n_estimators=50, max_depth=8, random_state=42)
        rf.fit(X, y)
        self.rf_model = rf

        preds = rf.predict(X)
        mae = float(mean_absolute_error(y, preds))
        rmse = float(np.sqrt(mean_squared_error(y, preds)))

        # Update metadata
        self.metadata = {
            "model_type": "RandomForestRegressor",
            "features": feature_cols,
            "n_samples": len(df),
            "test_size": 0.0,
            "evaluation_metrics": {
                "mae_hours": round(mae, 2),
                "rmse_hours": round(rmse, 2),
            },
            "is_synthetic": False,
            "disclaimer": f"Trained directly on {len(df)} real completed task records from your database.",
            "trained_at": pd.Timestamp.now().isoformat()
        }

        # Save to disk
        joblib.dump(rf, RF_MODEL_PATH)
        with open(METADATA_PATH, "w") as f:
            json.dump(self.metadata, f, indent=2)

        return {
            "success": True,
            "sample_count": len(df),
            "mae_hours": round(mae, 2),
            "rmse_hours": round(rmse, 2),
            "message": f"Successfully trained Random Forest model on {len(df)} real completed database tasks!"
        }

    def detect_workload_anomaly(
        self,
        utilization_percentage: float,
        weighted_remaining_effort: float,
        active_tasks_count: int
    ) -> Dict[str, Any]:
        """
        Uses Isolation Forest to detect outlier workload patterns.
        """
        if not self.iso_model:
            is_anomaly = utilization_percentage > 120.0 or (active_tasks_count > 10 and utilization_percentage > 90.0)
            return {
                "is_anomaly": is_anomaly,
                "anomaly_label": "Potential Overload Anomaly" if is_anomaly else "Normal Workload",
                "score": -0.5 if is_anomaly else 0.5
            }

        sample = np.array([[
            float(utilization_percentage),
            float(weighted_remaining_effort),
            int(active_tasks_count)
        ]])

        # Isolation forest returns -1 for anomaly, 1 for normal
        prediction = int(self.iso_model.predict(sample)[0])
        score = float(self.iso_model.decision_function(sample)[0])

        is_anomaly = (prediction == -1)
        anomaly_label = "Potential Overload Anomaly" if is_anomaly and utilization_percentage > 80.0 else (
            "Unusual Workload Pattern" if is_anomaly else "Normal Workload"
        )

        return {
            "is_anomaly": is_anomaly,
            "anomaly_label": anomaly_label,
            "anomaly_score": round(score, 3),
            "inputs": {
                "utilization_percentage": utilization_percentage,
                "weighted_remaining_effort": weighted_remaining_effort,
                "active_tasks_count": active_tasks_count
            }
        }

ml_engine = MLEngine()
